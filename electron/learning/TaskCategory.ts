/**
 * PiPiClaw — 任务类别归一（M4-D）
 *
 * 【为什么单独成模块】
 * 「这个技能有没有用」这个判断,需要把运行归到**任务类别**:
 * 同类任务的运行才能放在一起比 —— 否则「带技能的成功率 40%」既可能是
 * 技能没用,也可能是这批任务本身就难。
 *
 * 而归一规则**必须两侧完全一致**:
 *   - 记录侧(ChatManager)给「带技能的运行」打类别
 *   - 对比侧(tracker)按类别找「不带该技能的运行」
 * 两边规则稍有出入,对比组就会漏掉记录 → 差值算错。
 * 所以归一规则只能有一份,两个地方都从这里取。
 *
 * 【归一到什么程度】
 * 只做【表面形式】归一(大小写/标点/空白),不做语义归一。
 * 语义归一需要 embedding —— 那是后续批次的事(当前 embedding 仍是伪向量)。
 * 代价:「整理桌面」与「清理桌面」算两个类别 → 样本量偏少,
 * 但【口径诚实】比【看起来样本多】重要。
 */

/**
 * 把一条用户指令归一成任务类别键。
 *
 * 与 SelfLearner 观察去重用的是同一套规则 —— 同一件事在两处必须归到同一个键。
 */
export function normalizeTaskCategory(instruction: string): string {
  if (!instruction) return '';
  return instruction
    .toLowerCase()
    // 去除句号、感叹号、问号、逗号等标点
    .replace(/[.!,?;:'"()]/g, '')
    // 统一空白字符
    .replace(/\s+/g, ' ')
    // 去除首尾空格
    .trim();
}
